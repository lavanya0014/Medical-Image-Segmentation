def prediction_directory() -> Path:
    for directory in (PROJECT_ROOT / "c3_warmstart_predictions", PROJECT_ROOT / "c3_predictions"):
        if directory.is_dir():
            return directory
    raise FileNotFoundError("Could not find c3_warmstart_predictions or c3_predictions.")


def read(path: Path) -> np.ndarray:
    volume = nib.load(path).get_fdata(dtype=np.float32)
    if volume.ndim == 4 and volume.shape[-1] == 1:
        volume = volume[..., 0]
    if volume.ndim != 3:
        raise ValueError(f"Expected a 3-D NIfTI volume: {path}")
    return np.nan_to_num(volume)


def overlay(image: np.ndarray, prediction: np.ndarray, label: np.ndarray, slice_index: int) -> np.ndarray:
    source = image[:, :, slice_index].T
    low, high = np.percentile(source, (1, 99))
    gray = np.clip((source - low) / max(high - low, 1e-6), 0, 1)
    result = np.repeat((gray[..., None] * 255).astype(np.uint8), 3, axis=-1)
    prediction_mask = prediction[:, :, slice_index].T > 0
    label_mask = label[:, :, slice_index].T > 0
    result[label_mask & ~prediction_mask] = [45, 210, 85]
    result[prediction_mask & ~label_mask] = [235, 55, 55]
    result[prediction_mask & label_mask] = [255, 215, 0]
    return result


def score_case(prediction: np.ndarray, label: np.ndarray) -> float:
    prediction_mask = prediction > 0
    label_mask = label > 0
    return float(2 * np.logical_and(prediction_mask, label_mask).sum() / max(prediction_mask.sum() + label_mask.sum(), 1))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--examples", type=int, default=3)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError(f"Output already exists: {args.output}. Choose another --output path or remove that folder first.")

    prediction_dir = prediction_directory()
    candidates = []
    for label_path in sorted(LABELS_DIR.glob("*.nii.gz")):
        case = label_path.name
        prediction_path = prediction_dir / case
        image_path = IMAGES_DIR / case.replace(".nii.gz", "_0000.nii.gz")
        if not prediction_path.is_file() or not image_path.is_file():
            continue
        image, prediction, label = read(image_path), read(prediction_path), read(label_path)
        if image.shape != prediction.shape or image.shape != label.shape:
            continue
        candidates.append((score_case(prediction, label), image, prediction, label))
    if not candidates:
        raise RuntimeError("No matching image, label, and saved C3 prediction volumes were found.")

    candidates.sort(key=lambda item: item[0], reverse=True)
    selected = candidates[: args.examples]
    args.output.mkdir(parents=True)
    metadata = {}
    for index, (dice, image, prediction, label) in enumerate(selected, start=1):
        overlap_by_slice = np.logical_and(prediction > 0, label > 0).sum(axis=(0, 1))
        chosen_slice = int(np.argmax(overlap_by_slice))
        image_path = args.output / f"example_{index}.png"
        Image.fromarray(overlay(image, prediction, label, chosen_slice)).save(image_path, optimize=True)
        encoded_image = base64.b64encode(image_path.read_bytes()).decode("ascii")
        image_path.unlink()
        metadata[f"Example {index}"] = {"image": f"data:image/png;base64,{encoded_image}", "dice": dice}

    (args.output / "index.html").write_text(HTML_TEMPLATE.replace("__CASES__", json.dumps(metadata)))
    (args.output / "README.md").write_text(README_SOURCE)
    zip_path = shutil.make_archive(str(args.output), "zip", args.output)
    print(f"Created Space folder: {args.output}")
    print(f"Created upload zip: {zip_path}")
    print("Upload index.html to a new Hugging Face Static Space. It is a single self-contained file.")


if __name__ == "__main__":
    main()
